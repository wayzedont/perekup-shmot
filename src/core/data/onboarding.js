// Между главами обучения и после него Тимур подсказывает то, чего в главах
// не было, — ровно одним сообщением за раз и только когда это стало нужно:
// про подарок брата, про время в секонде, про книжку, про отзывы. Пишет он
// в Телегу, поэтому до неё советы ждут в очереди.
//
// Правило для текстов: один шаг говорит об одной вещи и заканчивается тем,
// что игроку делать дальше. Никаких «а ещё бывает» — остальное по ходу.

