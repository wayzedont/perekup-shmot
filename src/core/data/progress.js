/** Кредитная история: закрытые без просрочек кредиты поднимают планку. */
export function historyCap(history) {
  const clean = history.paidClean || 0;
  const missed = history.missed || 0;
  return Math.max(3000, 5000 + 7000 * clean - 6000 * missed);
}

